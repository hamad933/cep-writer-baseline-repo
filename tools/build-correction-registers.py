    old, new = before.get(relative), after.get(relative)
    old_hash, new_hash = digest(old) if old else None, digest(new) if new else None
    if old_hash == new_hash:
        continue
    status = "ADDED" if old is None else "DELETED" if new is None else "MODIFIED"
    rows.append({
        "path": relative,
        "status": status,
        "baselineBytes": old.stat().st_size if old else None,
        "candidateBytes": new.stat().st_size if new else None,
        "baselineSha256": old_hash,
        "candidateSha256": new_hash,
    })

